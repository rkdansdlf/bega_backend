package com.example.cheerboard.retention;

/** 신고 증거 미디어의 보관 상태. 계정 삭제 가드(purge 보류)와는 독립된 상태다. */
public enum ReportEvidenceMediaStatus {
    /** 보관 중. 기본 보관 기한과 연장 승인, 법적 보존 근거에 따라 만료 여부가 결정된다. */
    ACTIVE,
    /** 만료되었거나 사건이 종료되어 저장소 객체를 삭제해야 한다. 실패하면 재시도한다. */
    DELETE_PENDING,
    /** 저장소 객체와 이미지 행을 삭제했다. */
    DELETED,
    /** 기존 데이터처럼 최초 삭제 요청일이 불명확해서 자동 삭제하지 않고 사전 검토한다. */
    REVIEW_REQUIRED,
    /**
     * 사건이 열려 있는데 기본 보관 기한(또는 90일 상한)이 지났다. 즉시 삭제하지 않고 긴급 관리자 검토 대상으로 둔다.
     * 검토 유예는 행마다 한 번만 주며 최대 24시간이다. 유예가 끝나도 결정이 없으면 삭제 대상이 된다.
     */
    URGENT_REVIEW,
    /** 소유자가 복구되어 삭제 절차가 끝났다. 감사를 위해 행은 남기고, 더 이상 보관 판단을 하지 않는다. */
    RESOLVED_RESTORED
}
