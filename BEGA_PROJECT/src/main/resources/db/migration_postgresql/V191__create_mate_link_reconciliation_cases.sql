CREATE TABLE mate_link_recon_cases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_key VARCHAR(140) NOT NULL,
    party_id BIGINT,
    application_id BIGINT,
    payment_transaction_id BIGINT,
    reason_code VARCHAR(48) NOT NULL,
    observed_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_mlrc_case_key UNIQUE (case_key)
);

CREATE INDEX idx_mlrc_observed_id
    ON mate_link_recon_cases(observed_at, id);
