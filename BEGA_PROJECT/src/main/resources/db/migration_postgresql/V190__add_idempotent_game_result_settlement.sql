-- Preserve the cutover classification so only previously unsettled predictions are reprocessed.
ALTER TABLE predictions
    ADD COLUMN score_settlement_status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    ADD COLUMN score_settled_at TIMESTAMP;

UPDATE predictions SET score_settlement_status = 'LEGACY';

CREATE TABLE game_result_settlement_baseline (
    id BIGINT PRIMARY KEY,
    cutoff_prediction_id BIGINT NOT NULL,
    last_prediction_id BIGINT NOT NULL,
    is_complete BOOLEAN NOT NULL DEFAULT FALSE,
    pending_game_cursor VARCHAR(255)
);

INSERT INTO game_result_settlement_baseline (
    id, cutoff_prediction_id, last_prediction_id, is_complete, pending_game_cursor
)
SELECT 1, COALESCE(MAX(id), 0), 0, FALSE, NULL
FROM predictions;

CREATE TABLE legacy_perfect_day_dates (
    game_date DATE PRIMARY KEY
);

CREATE TABLE perfect_day_settlement_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    game_date DATE NOT NULL,
    games_won INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_perfect_day_receipt_user_date UNIQUE (user_id, game_date)
);

CREATE INDEX idx_predictions_settlement_status_game
    ON predictions (score_settlement_status, game_id);
