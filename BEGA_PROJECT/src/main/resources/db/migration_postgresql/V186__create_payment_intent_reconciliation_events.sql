CREATE TABLE payment_intent_reconciliation_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_intent_id BIGINT NOT NULL,
    event_type VARCHAR(40) NOT NULL,
    requested_payment_key VARCHAR(200),
    candidate_payment_key VARCHAR(200),
    candidate_order_id VARCHAR(100),
    candidate_amount INTEGER,
    candidate_status VARCHAR(30),
    verified_payment_key VARCHAR(200),
    verified_order_id VARCHAR(100),
    verified_amount INTEGER,
    verified_status VARCHAR(30),
    evidence_reference VARCHAR(300),
    recorded_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_pire_intent_event_created
    ON payment_intent_reconciliation_events(payment_intent_id, event_type, created_at);
