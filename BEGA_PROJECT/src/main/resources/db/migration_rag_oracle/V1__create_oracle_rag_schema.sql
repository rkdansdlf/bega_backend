-- Canonical Oracle RAG schema. This is a fresh-schema migration: existing
-- objects are a reconciliation concern and must not be silently adopted.
-- Oracle 23.6+ is required because manual ingest performs DML after the HNSW
-- index exists. The migration contains no corpus rows or environment grants.

CREATE TABLE rag_chunks (
    id                 NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    source_table       VARCHAR2(128 CHAR) NOT NULL,
    source_row_id      VARCHAR2(512 CHAR) NOT NULL,
    title              CLOB NOT NULL,
    content            CLOB NOT NULL,
    meta               CLOB DEFAULT '{}' NOT NULL,
    content_hash       VARCHAR2(64 CHAR) NOT NULL,
    index_version      VARCHAR2(64 CHAR) DEFAULT 'rag-v1' NOT NULL,
    index_status       VARCHAR2(16 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    indexed_at         TIMESTAMP(6) NOT NULL,
    embedding_vector   VECTOR(1536, FLOAT32),
    season_year        NUMBER(4),
    team_id            VARCHAR2(64 CHAR),
    league_type_code   VARCHAR2(64 CHAR),
    player_id          VARCHAR2(128 CHAR),
    created_at         TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at         TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_rag_chunks PRIMARY KEY (id),
    CONSTRAINT uq_rag_chunks_source UNIQUE (source_table, source_row_id),
    CONSTRAINT ck_rag_chunks_status
        CHECK (index_status IN ('ACTIVE', 'INDEXED', 'DELETED')),
    CONSTRAINT ck_rag_chunks_meta_json CHECK (meta IS JSON)
);

CREATE TABLE rag_chunk_terms (
    rag_chunk_id   NUMBER(19) NOT NULL,
    source_table   VARCHAR2(128 CHAR) NOT NULL,
    token          VARCHAR2(128 CHAR) NOT NULL,
    term_count     NUMBER(10) NOT NULL,
    title_count    NUMBER(10) DEFAULT 0 NOT NULL,
    game_date      VARCHAR2(32 CHAR),
    CONSTRAINT pk_rag_chunk_terms PRIMARY KEY (rag_chunk_id, token),
    CONSTRAINT fk_rag_chunk_terms_chunk FOREIGN KEY (rag_chunk_id)
        REFERENCES rag_chunks (id) ON DELETE CASCADE,
    CONSTRAINT ck_rag_chunk_terms_counts
        CHECK (term_count > 0 AND title_count >= 0 AND title_count <= term_count)
);

CREATE INDEX idx_rag_chunks_filter
    ON rag_chunks (source_table, index_status, season_year, team_id, player_id, league_type_code);

CREATE INDEX idx_rag_chunks_lifecycle
    ON rag_chunks (index_status, updated_at);

CREATE INDEX idx_rag_terms_token_score
    ON rag_chunk_terms (token, term_count DESC, title_count DESC, rag_chunk_id);

CREATE INDEX idx_rag_terms_source_date
    ON rag_chunk_terms (source_table, game_date, token, rag_chunk_id);

CREATE VECTOR INDEX IDX_RAG_CHUNKS_EMBEDDING_HNSW
    ON rag_chunks (embedding_vector)
    ORGANIZATION INMEMORY NEIGHBOR GRAPH
    DISTANCE COSINE
    WITH TARGET ACCURACY 95;
