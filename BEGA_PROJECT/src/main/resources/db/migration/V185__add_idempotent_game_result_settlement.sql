-- Preserve the cutover classification so only previously unsettled predictions are reprocessed.
ALTER TABLE predictions ADD (
    score_settlement_status VARCHAR2(16) DEFAULT 'PENDING' NOT NULL,
    score_settled_at TIMESTAMP(6)
);

UPDATE predictions SET score_settlement_status = 'LEGACY';

CREATE TABLE game_result_settlement_baseline (
    id NUMBER(19,0) NOT NULL,
    cutoff_prediction_id NUMBER(19,0) NOT NULL,
    last_prediction_id NUMBER(19,0) NOT NULL,
    is_complete NUMBER(1,0) DEFAULT 0 NOT NULL,
    pending_game_cursor VARCHAR2(255),
    CONSTRAINT pk_game_result_settlement_baseline PRIMARY KEY (id),
    CONSTRAINT ck_game_result_settlement_baseline_complete CHECK (is_complete IN (0, 1))
);

INSERT INTO game_result_settlement_baseline (
    id, cutoff_prediction_id, last_prediction_id, is_complete, pending_game_cursor
)
SELECT 1, NVL(MAX(id), 0), 0, 0, NULL
FROM predictions;

CREATE TABLE legacy_perfect_day_dates (
    game_date DATE NOT NULL,
    CONSTRAINT pk_legacy_perfect_day_dates PRIMARY KEY (game_date)
);

CREATE TABLE perfect_day_settlement_receipts (
    id NUMBER(19,0) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id NUMBER(19,0) NOT NULL,
    game_date DATE NOT NULL,
    games_won NUMBER(10,0) NOT NULL,
    created_at TIMESTAMP(6) DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_perfect_day_settlement_receipts PRIMARY KEY (id),
    CONSTRAINT uk_perfect_day_receipt_user_date UNIQUE (user_id, game_date)
);

CREATE INDEX idx_predictions_settlement_status_game
    ON predictions (score_settlement_status, game_id);
