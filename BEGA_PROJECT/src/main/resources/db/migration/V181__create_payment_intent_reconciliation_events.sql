CREATE TABLE payment_intent_reconciliation_events (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    payment_intent_id NUMBER NOT NULL,
    event_type VARCHAR2(40) NOT NULL,
    requested_payment_key VARCHAR2(200),
    candidate_payment_key VARCHAR2(200),
    candidate_order_id VARCHAR2(100),
    candidate_amount NUMBER(10),
    candidate_status VARCHAR2(30),
    verified_payment_key VARCHAR2(200),
    verified_order_id VARCHAR2(100),
    verified_amount NUMBER(10),
    verified_status VARCHAR2(30),
    evidence_reference VARCHAR2(300),
    recorded_by NUMBER,
    created_at TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX idx_pire_intent_event_created
    ON payment_intent_reconciliation_events(payment_intent_id, event_type, created_at);
