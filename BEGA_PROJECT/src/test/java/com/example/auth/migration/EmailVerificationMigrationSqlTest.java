package com.example.auth.migration;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.LinkedHashMap;
import java.util.Map;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;

class EmailVerificationMigrationSqlTest {

    private static final String MIGRATION = "db/migration_postgresql/V182__add_email_verification.sql";

    @Test
    @DisplayName("V182 grandfathers existing users (incl. monitor account) as verified and keeps DB default TRUE for rollback safety")
    void existingUsersAreGrandfatheredAndDbDefaultStaysTrue() throws Exception {
        try (Connection connection = DriverManager.getConnection(
                "jdbc:h2:mem:email_verification_migration;MODE=PostgreSQL;DB_CLOSE_DELAY=-1",
                "sa",
                "")) {
            execute(connection, "CREATE TABLE users (id BIGSERIAL PRIMARY KEY, email VARCHAR(255) NOT NULL UNIQUE)");
            execute(connection, "INSERT INTO users(email) VALUES "
                    + "('existing@example.com'), ('baseballguide251021+monitor@gmail.com')");

            executeStatements(connection, loadSql(MIGRATION));

            // 이전 이미지(컬럼을 모르는 INSERT)로 롤백돼도 새 계정이 잠기지 않도록 DB 기본값은 TRUE 다.
            // 애플리케이션은 이메일 가입 시 false 를 명시적으로 넣는다.
            execute(connection, "INSERT INTO users(email) VALUES ('after-migration@example.com')");
            execute(connection, "INSERT INTO users(email, email_verified) VALUES ('explicit-unverified@example.com', FALSE)");

            assertThat(readVerified(connection))
                    .containsEntry("existing@example.com", true)
                    .containsEntry("baseballguide251021+monitor@gmail.com", true)
                    .containsEntry("after-migration@example.com", true)
                    .containsEntry("explicit-unverified@example.com", false);

            Long userId = queryLong(connection, "SELECT id FROM users WHERE email = 'after-migration@example.com'");
            execute(connection, "INSERT INTO email_verification_tokens(user_id, token_digest, created_at, expiry_date) "
                    + "VALUES (" + userId + ", 'digest-1', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)");
            assertThat(queryLong(connection, "SELECT COUNT(*) FROM email_verification_tokens WHERE used = FALSE"))
                    .isEqualTo(1L);
        }
    }

    @Test
    @DisplayName("V182 is PostgreSQL-only SQL (no Oracle syntax)")
    void migrationDoesNotUseOracleSyntax() throws Exception {
        String sql = loadSql(MIGRATION).toUpperCase();
        assertThat(sql).doesNotContain("VARCHAR2").doesNotContain("NUMBER(").doesNotContain("GENERATED BY DEFAULT ON NULL");
        assertThat(sql).contains("ADD COLUMN IF NOT EXISTS EMAIL_VERIFIED BOOLEAN NOT NULL DEFAULT TRUE");
        assertThat(sql).doesNotContain("SET DEFAULT FALSE").doesNotContain("ALTER COLUMN EMAIL_VERIFIED");
    }

    private Map<String, Boolean> readVerified(Connection connection) throws SQLException {
        Map<String, Boolean> values = new LinkedHashMap<>();
        try (Statement statement = connection.createStatement();
                ResultSet resultSet = statement.executeQuery("SELECT email, email_verified FROM users ORDER BY id")) {
            while (resultSet.next()) {
                values.put(resultSet.getString("email"), resultSet.getBoolean("email_verified"));
            }
        }
        return values;
    }

    private Long queryLong(Connection connection, String sql) throws SQLException {
        try (Statement statement = connection.createStatement();
                ResultSet resultSet = statement.executeQuery(sql)) {
            resultSet.next();
            return resultSet.getLong(1);
        }
    }

    private void executeStatements(Connection connection, String sql) throws SQLException {
        for (String statement : sql.split(";")) {
            String trimmed = statement.trim();
            if (!trimmed.isEmpty() && !isCommentOnly(trimmed)) {
                execute(connection, trimmed);
            }
        }
    }

    private boolean isCommentOnly(String chunk) {
        return chunk.lines().map(String::trim).allMatch(line -> line.isEmpty() || line.startsWith("--"));
    }

    private void execute(Connection connection, String sql) throws SQLException {
        try (Statement statement = connection.createStatement()) {
            statement.execute(sql);
        }
    }

    private String loadSql(String resourcePath) throws IOException {
        ClassPathResource resource = new ClassPathResource(resourcePath);
        try (var inputStream = resource.getInputStream()) {
            return new String(inputStream.readAllBytes(), StandardCharsets.UTF_8);
        }
    }
}
